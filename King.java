
public class King {
    King(String name, String kingdom) {
        this.name = name;
    }

    King(int reignYears) {
        this.reignYears = reignYears;
    }

    King(boolean isCurrent) {
        this.isCurrent = isCurrent;
    }

    King(String dynasty) {
        this.dynasty = dynasty;
    }

    String name;
    String kingdom;
    int reignYears;
    boolean isCurrent;
    String dynasty;
}

