class Tyre {
    static String brand;
    static int size;
    static boolean isTubeless;
    static String type;
    static double pressure;

    public static String getBrand() {
        return brand;
    }

    public static int getSize() {
        return size;
    }

    public static boolean isTubeless() {
        return isTubeless;
    }

    public static String getType() {
        return type;
    }

    public static double getPressure() {
        return pressure;
    }
}