class Clothes {
    static String type;
    static String size;
    static String color;
    static String material;
    static boolean isWashed;

    public static String getType() {
        return type;
    }

    public static String getSize() {
        return size;
    }

    public static String getColor() {
        return color;
    }

    public static String getMaterial() {
        return material;
    }

    public static boolean isWashed() {
        return isWashed;
    }
}