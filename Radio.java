class Radio {
    static String brand;
    static double frequency;
    static boolean isPortable;
    static int volume;
    static String color;

    public static String getBrand() {
        return brand;
    }

    public static double getFrequency() {
        return frequency;
    }

    public static boolean isPortable() {
        return isPortable;
    }

    public static int getVolume() {
        return volume;
    }

    public static String getColor() {
        return color;
    }
}