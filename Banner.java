class Banner {
    static String message;
    static String color;
    static int width;
    static int height;
    static boolean isPrinted;

    public static String getMessage() {
        return message;
    }

    public static String getColor() {
        return color;
    }

    public static int getWidth() {
        return width;
    }

    public static int getHeight() {
        return height;
    }

    public static boolean isPrinted() {
        return isPrinted;
    }
}