class Market {
    static String name;
    static String location;
    static int numberOfShops;
    static String marketType;
    static String openingHours;

    public static String getName() {
        return name;
    }

    public static String getLocation() {
        return location;
    }

    public static int getNumberOfShops() {
        return numberOfShops;
    }

    public static String getMarketType() {
        return marketType;
    }

    public static String getOpeningHours() {
        return openingHours;
    }
}